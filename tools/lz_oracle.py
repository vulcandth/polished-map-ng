"""Compile pinned, unchanged master LZ loading and bitplane parsing functions.

The driver accepts only the bounded synthetic corpus generated by the Rust test.
Do not feed malformed streams to upstream: its decoder contains unchecked reads
and writes. Generated source stays in ignored scratch storage (LGPL-3.0-only).
"""
import argparse
import hashlib
import json
from pathlib import Path
import subprocess

REVISION = "8b9bdc2b8aac8c865809516c2123af69c498da0b"


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument("--checkout", type=Path, required=True)
    p.add_argument("--output", type=Path, required=True)
    p.add_argument("--cxx", default="g++")
    p.add_argument("--git", default="git")
    args = p.parse_args()
    sources = {name: subprocess.check_output([
        args.git, "-C", str(args.checkout), "show", f"{REVISION}:src/{name}"
    ]).decode("utf-8") for name in ["tiled-image.cpp", "tiled-image.h", "tile.h", "palette-map.h", "colors.h", "utils.cpp"]}
    evidence = []

    def snippet(name, start, end):
        source = sources[name]
        a = source.index(start)
        b = source.index(end, a) + len(end)
        text = source[a:b]
        evidence.append({"source": f"src/{name}", "start": start, "sha256": hashlib.sha256(text.encode()).hexdigest(), "changes": []})
        return text

    macros = []
    for name, prefix in [("tile.h", "#define TILE_SIZE "), ("tile.h", "#define TILE_AREA "),
                         ("palette-map.h", "#define MAX_NUM_TILES "), ("tiled-image.h", "#define BYTES_PER_2BPP_TILE ")]:
        macros.append(snippet(name, prefix, "\n"))
    hue = snippet("colors.h", "enum class Hue", ";")
    result = snippet("tiled-image.h", "enum class Result", ";")
    commands = snippet("tiled-image.cpp", "enum class Lz_Command", "})();")
    file_size = snippet("utils.cpp", "size_t file_size(FILE *f)", "\n}")
    convert = snippet("tiled-image.cpp", "static void convert_2bytes_to_8hues(", "\n}")
    parse = snippet("tiled-image.cpp", "Tiled_Image::Result Tiled_Image::parse_2bpp_data(", "\n}")
    load = snippet("tiled-image.cpp", "Tiled_Image::Result Tiled_Image::read_lz_graphics(", "\n}")
    header = r'''
// Copyright Rangi42/Polished Map contributors; driver: Polished Map NG. LGPL-3.0-only.
#ifndef _DEFAULT_SOURCE
#define _DEFAULT_SOURCE 1
#endif
#include <array>
#include <vector>
#include <cstdint>
#include <cstdio>
#include <fstream>
#include <iostream>
#include <string>
#include <sys/stat.h>
using uchar = unsigned char;
// UTF-8 test paths are ASCII. This is the only FLTK adapter in this harness.
FILE *fl_fopen(const char *path, const char *mode) { return std::fopen(path, mode); }
'''
    stub = r'''
struct Tiled_Image {
''' + result + r'''
    std::vector<Hue> _tile_hues;
    size_t _num_tiles = 0;
    Result _result = Result::IMG_NULL;
    Result parse_2bpp_data(const std::vector<uchar>&);
    Result read_lz_graphics(const char*);
};
'''
    driver = r'''
bool read32(std::istream &in, uint32_t &value) {
    unsigned char b[4]; if (!in.read((char*)b,4)) return false;
    value = uint32_t(b[0]) | uint32_t(b[1])<<8 | uint32_t(b[2])<<16 | uint32_t(b[3])<<24;
    return true;
}
void write32(std::ostream &out, uint32_t value) {
    for(int i=0;i<4;++i) out.put(char(value>>(8*i)));
}
int main(int argc,char **argv) {
    if(argc!=4) return 2;
    std::ifstream input(argv[1], std::ios::binary);
    std::ofstream output(argv[2], std::ios::binary);
    uint32_t count=0; if(!read32(input,count) || count>20000) return 3;
    for(uint32_t index=0;index<count;++index) {
        uint32_t size=0; if(!read32(input,size) || size>8192) return 4;
        std::vector<char> bytes(size); if(!input.read(bytes.data(),size)) return 5;
        { std::ofstream file(argv[3],std::ios::binary|std::ios::trunc);
          file.write(bytes.data(),size); if(!file.good()) return 6; }
        Tiled_Image image;
        auto result=image.read_lz_graphics(argv[3]);
        write32(output,uint32_t(result));
        write32(output,uint32_t(image._num_tiles));
        for(Hue hue:image._tile_hues) output.put(char(hue));
        if(!output.good()) return 7;
    }
    if(input.peek()!=EOF) return 8;
    return 0;
}
'''
    args.output.parent.mkdir(parents=True, exist_ok=True)
    cpp = args.output.with_suffix(".cpp")
    cpp.write_text(header + "\n".join(macros) + hue + stub + commands + file_size + convert + parse + load + driver, encoding="utf-8")
    args.output.with_suffix(".provenance.json").write_text(json.dumps({"revision": REVISION, "functions_and_constants": evidence,
        "adapters": ["fl_fopen uses std::fopen for synthetic ASCII paths", "minimal Tiled_Image declaration exposes original result and hue buffers"]}, indent=2)+"\n", encoding="utf-8")
    subprocess.run([args.cxx, "-std=c++17", "-O2", str(cpp), "-o", str(args.output)], check=True)


if __name__ == "__main__":
    main()
